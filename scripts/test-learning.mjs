import {registerHooks} from 'node:module';
import assert from 'node:assert/strict';
registerHooks({resolve(s,c,next){return next(s.startsWith('.') && !/\.[a-z]+$/.test(s) ? s+'.ts' : s,c);}});
const {publishedLessons} = await import('../src/lessons.ts');
const {recordSchema,SESSION_CAP} = await import('../shared/record.ts');
const {finishProblems,prepareRecord,courseProgress,lessonWorkProgress} = await import('../shared/learning.ts');
const {applyTimed,activeDelta,correctTotal,IDLE_MS} = await import('../src/timing.ts');
const lesson = publishedLessons.find(l=>l.id==='week1-day1-v1');
const base={version:1,notes:'',submission:'',minutes:0,status:'practicing',updatedAt:''};
const fields=lesson.apprenticeship.worksheet.flatMap(s=>s.fields);
assert.equal(fields.length,36);
assert.equal(new Set(lesson.flow.map(a=>a.id)).size,lesson.flow.length);
assert.deepEqual(lesson.flow.filter(a=>a.kind==='field').map(a=>a.field).sort(),fields.map(f=>f.id).sort());
const complete={...base,worksheet:Object.fromEntries(fields.map(f=>[f.id,f.options?.[0] || 'QA: one clear answer.'])),learning:{completed:['welcome','see-example'],answers:{}}};
lesson.apprenticeship.checks.forEach((c,i)=>complete.learning.answers[`check-${i+1}`]={value:c.options[1].label,shown:true});
const sorter=lesson.apprenticeship.guide.find(g=>g.sorter).sorter;
sorter.items.forEach(item=>complete.learning.answers[`sort-${item.id}`]={value:sorter.options[0],shown:true});
assert.deepEqual(finishProblems(lesson,complete),[], 'Incorrect formative choices never block completion');
assert.ok(finishProblems(lesson,base).length);
assert.ok(finishProblems(lesson,{...complete,worksheet:{...complete.worksheet,'entry-1-label':'not a label'}}).length);
const ready={...complete,status:'ready-for-review'};
assert.equal(prepareRecord(base,ready).status,'ready-for-review','Worksheet-only review survives the save hook');
assert.ok(recordSchema.safeParse(ready).success);
const finished={...complete,learning:{...complete.learning,finishedAt:new Date().toISOString()}};
assert.equal(lessonWorkProgress(lesson,finished).percent,100);
const external={...base,notes:'Reflection on the supplied walkthrough',submission:'My local practice file',learning:{...finished.learning,route:'external',outputsConfirmed:true,repair:'Separated my guesses from visible facts'}};
assert.deepEqual(finishProblems(lesson,external),[]);
const externalProgress=lessonWorkProgress(lesson,external);
assert.equal(externalProgress.done,externalProgress.total,'External route fills its own progress denominator');
assert.equal(externalProgress.percent,100);
const missingSort={...external,learning:{...external.learning,finishedAt:undefined,answers:Object.fromEntries(Object.entries(external.learning.answers).filter(([id])=>!id.startsWith('sort-')))}};
assert.equal(lessonWorkProgress(lesson,missingSort).done,externalProgress.done-7,'Six sorter attempts and explicit finish remain required');
assert.equal(prepareRecord(finished,{...finished,minutes:30}).learning.finishedAt,finished.learning.finishedAt);
assert.equal(prepareRecord(finished,{...finished,worksheet:{...finished.worksheet,app:'Changed work'}}).learning.finishedAt,undefined);
assert.equal(courseProgress(publishedLessons,[{lessonId:lesson.id,record:finished}]).finished,1);
assert.equal(courseProgress(publishedLessons,[{lessonId:'baseline-v1',record:finished}]).finished,0);
const optional=publishedLessons.find(l=>l.optional);
assert.equal(courseProgress(publishedLessons,[{lessonId:optional.id,record:finished}]).finished,0);
assert.equal(courseProgress(publishedLessons,[{lessonId:lesson.id,record:ready}]).finished,0);
const segment={id:'d8b8a9b0-1111-4111-8111-000000000001',startedAt:'2026-09-12T12:00:00Z',elapsedMs:45000,step:2};
let timed=applyTimed(base,segment);
assert.equal(timed.minutes,0); assert.equal(timed.timingRemainderMs,45000);
assert.deepEqual(applyTimed(timed,segment),timed,'Reloading the same checkpoint is idempotent');
timed=applyTimed(timed,{...segment,elapsedMs:70000});
assert.equal(timed.minutes,1); assert.equal(timed.timingRemainderMs,10000);
timed=applyTimed(timed,{...segment,id:'d8b8a9b0-1111-4111-8111-000000000002',elapsedMs:50000,step:3});
assert.equal(timed.minutes,2); assert.equal(timed.timingRemainderMs,0,'Remainders survive changing steps');
assert.deepEqual(applyTimed(timed,segment),timed,'An older checkpoint cannot add time');
assert.equal(activeDelta(1000,IDLE_MS*3,1000),IDLE_MS,'Idle cutoff is bounded');
assert.equal(activeDelta(1000,500,1000),0,'Clock rollback cannot subtract time');
const adjusted=correctTotal(timed,1);
assert.equal(adjusted.minutes,1); assert.ok(adjusted.sessions.reduce((n,s)=>n+s.minutes,0)<=1);
assert.equal(applyTimed(adjusted,{...segment,elapsedMs:70000}).minutes,1,'Corrections retain replay protection');
assert.deepEqual(recordSchema.parse(base),base,'Old backups remain unchanged');
assert.ok(recordSchema.safeParse(finished).success);
assert.ok(!recordSchema.safeParse({...finished,learning:{...finished.learning,answers:Object.fromEntries(Array.from({length:31},(_,i)=>[`q-${i}`,{value:'x',shown:true}]))}}).success);
console.log(`Learning and timer regression checks passed. ${fields.length} stable worksheet fields; ${lesson.flow.length} actions; ${courseProgress(publishedLessons,[]).total} required lessons.`);
export {complete, base, lesson, segment};
